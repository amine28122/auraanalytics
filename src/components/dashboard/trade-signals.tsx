type UserProfile = {
  language?: 'en' | 'ar' | 'es';
}

type TradeSignal = AITradeSignal & { chartImage?: string };

const SignalCard = ({ signal, lang }: { signal: TradeSignal; lang: 'en' | 'ar' }) => {
    const t = translations[lang];
    const isBuy = signal.type === 'BUY';
    const isMarketOrder = signal.orderType === 'Market';

    return (
        <div className="rounded-lg border bg-card p-4 transition-all hover:shadow-md">
            <div className="flex items-center justify-between">
                <div className="flex items-center gap-3">
                    {isBuy ? (
                        <div className="rounded-full bg-green-500/10 p-2 text-green-500">
                            <ArrowUp className="h-5 w-5" />
                        </div>
                    ) : (
                        <div className="rounded-full bg-red-500/10 p-2 text-red-500">
                            <ArrowDown className="h-5 w-5" />
                        </div>
                    )}
                    <div className="flex flex-col">
                        <span className={`text-lg font-bold ${isBuy ? 'text-green-500' : 'text-red-500'}`}>
                            {isBuy ? t.buy : t.sell}
                        </span>
                        <Badge variant={isMarketOrder ? "default" : "secondary"} className="w-fit">
                            {isMarketOrder ? `${t.now}: ${signal.entryPrice}` : `${t.pending}: ${signal.entryPrice}`}
                        </Badge>
                    </div>
                </div>
            </div>
            <Separator className="my-3" />
            <div className="space-y-3 text-sm">
                <div className="flex items-center justify-between">
                    <span className="flex items-center gap-2 text-muted-foreground"><Crosshair className="h-4 w-4" /> {t.entry}</span>
                    <span className="font-mono font-medium">{signal.entryPrice}</span>
                </div>
                <div className="flex items-center justify-between">
                    <span className="flex items-center gap-2 text-muted-foreground"><CheckCircle className="h-4 w-4 text-green-500" /> {t.takeProfit}</span>
                    <div className="flex flex-col items-end font-mono font-medium text-green-500">
                        {signal.takeProfit.map((tp, i) => <span key={i}>{tp}</span>)}
                    </div>
                </div>
                 <div className="flex items-center justify-between">
                    <span className="flex items-center gap-2 text-muted-foreground"><DollarSign className="h-4 w-4 text-red-500" /> {t.stopLoss}</span>
                    <span className="font-mono font-medium text-red-500">{signal.stopLoss}</span>
                </div>
            </div>
        </div>
    )
}

export function TradeSignals({ result }: { result: AnalysisFormState | void }) {
  const { user } = useAuth();
  const { firestore } = useFirebase();
  const [userProfile, setUserProfile] = useState<UserProfile | null>(null);
  const [isSharing, setIsSharing] = useState(false);
  const shareableImageRef = useRef<HTMLDivElement>(null);
  const [currentTheme, setCurrentTheme] = useState<'light' | 'dark'>('dark');

  useEffect(() => {
    const theme = document.documentElement.classList.contains('dark') ? 'dark' : 'light';
    setCurrentTheme(theme);

    const observer = new MutationObserver(() => {
      const newTheme = document.documentElement.classList.contains('dark') ? 'dark' : 'light';
      setCurrentTheme(newTheme);
    });
    observer.observe(document.documentElement, { attributes: true, attributeFilter: ['class'] });
    return () => observer.disconnect();
  }, []);

  useEffect(() => {
    if (user && firestore) {
      const userDocRef = doc(firestore, 'users', user.uid);
      const unsubscribe = onSnapshot(userDocRef, (doc) => {
        if (doc.exists()) {
          setUserProfile(doc.data() as UserProfile);
        }
      });
      return () => unsubscribe();
    }
  }, [user, firestore]);
  
  const lang = userProfile?.language === 'ar' ? 'ar' : 'en';
  const t = translations[lang];

  const dataURLtoFile = (dataurl: string, filename: string) => {
      let arr = dataurl.split(','),
          mime = arr[0].match(/:(.*?);/)![1],
          bstr = atob(arr[1]), 
          n = bstr.length, 
          u8arr = new Uint8Array(n);
          
      while(n--){
          u8arr[n] = bstr.charCodeAt(n);
      }
      return new File([u8arr], filename, {type:mime});
  }

  const handleShare = async () => {
    if (!shareableImageRef.current || !result?.data) return;
    setIsSharing(true);
    try {
        const dataUrl = await toPng(shareableImageRef.current, { cacheBust: true, pixelRatio: 2 });
        const fileName = `aura-academy-analysis-${Date.now()}.png`;
        const file = dataURLtoFile(dataUrl, fileName);

        if (navigator.canShare && navigator.canShare({ files: [file] })) {
            await navigator.share({
                files: [file],
                title: 'AURA ACADEMY Analysis',
                text: 'Check out this trade analysis from AURA ACADEMY.',
            });
        } else {
            // Fallback for browsers that don't support Web Share API or sharing files
            const link = document.createElement('a');
            link.download = fileName;
            link.href = dataUrl;
            link.click();
        }
    } catch (err) {
        console.error('Failed to generate or share image', err);
    } finally {
        setIsSharing(false);
    }
  };


  if (!result || (!result.data && !result.error)) {
    return (
      <Card className="flex flex-col items-center justify-center card-glow">
        <CardHeader>
          <CardTitle className="font-headline text-2xl">{t.analysisResults}</CardTitle>
        </CardHeader>
        <CardContent className="flex flex-col items-center justify-center text-center">
          <AuraAcademyLogo iconOnly className="h-16 w-16 text-muted-foreground opacity-30" />
          <p className="mt-4 text-muted-foreground">{t.yourSignals}</p>
        </CardContent>
      </Card>
    );
  }

  const { data, chartImage } = result;

  if (!data) {
     return (
      <Card className="flex flex-col items-center justify-center card-glow">
        <CardHeader>
          <CardTitle className="font-headline text-2xl">{t.analysisResults}</CardTitle>
        </CardHeader>
        <CardContent className="flex flex-col items-center justify-center text-center">
          <AuraAcademyLogo iconOnly className="h-16 w-16 text-muted-foreground opacity-30" />
          <p className="mt-4 text-muted-foreground">{t.noData}</p>
        </CardContent>
      </Card>
    );
  }

  const confidencePercentage = Math.round(data.confidenceLevel * 100);

  return (
    <>
      <Card dir={lang === 'ar' ? 'rtl' : 'ltr'} className="card-glow">
        <CardHeader className="flex flex-row items-start justify-between">
            <div>
                <CardTitle>{t.analysisResults}</CardTitle>
                <CardDescription>{t.generatedBy}</CardDescription>
            </div>
            <Button variant="outline" size="sm" onClick={handleShare} disabled={isSharing}>
                {isSharing ? <Loader2 className="mr-2 h-4 w-4 animate-spin" /> : <Share2 className="mr-2 h-4 w-4" />}
                {isSharing ? t.sharing : t.share}
            </Button>
        </CardHeader>
        <CardContent className="space-y-6">
          <div>
            <h3 className="mb-2 flex items-center gap-2 text-lg font-semibold">
              <Lightbulb className="h-5 w-5 text-primary" />
              {t.technicalSummary}
            </h3>
            <p className="text-sm text-muted-foreground">{data.analysisSummary}</p>
          </div>

          <div>
            <h3 className="mb-2 text-lg font-semibold">{t.confidenceLevel}</h3>
            <div className="flex items-center gap-4">
              <Progress value={confidencePercentage} className="w-full" />
              <span className="font-mono text-lg font-medium text-primary">{confidencePercentage}%</span>
            </div>
          </div>
          
          <div className="grid grid-cols-1 gap-4 sm:grid-cols-2">
              <div>
                  <h3 className="mb-2 flex items-center gap-2 text-lg font-semibold">
                      <TrendingDown className="h-5 w-5 text-green-400" />
                      {t.supportLevels}
                  </h3>
                  <div className="flex flex-wrap gap-2">
                      {data.supportLevels.map((level, i) => <Badge key={i} variant="outline" className="font-mono">{level}</Badge>)}
                  </div>
              </div>
              <div>
                  <h3 className="mb-2 flex items-center gap-2 text-lg font-semibold">
                      <TrendingUp className="h-5 w-5 text-red-400" />
                      {t.resistanceLevels}
                  </h3>
                  <div className="flex flex-wrap gap-2">
                      {data.resistanceLevels.map((level, i) => <Badge key={i} variant="outline" className="font-mono">{level}</Badge>)}
                  </div>
              </div>
          </div>

          <div>
              <h3 className="mb-4 flex items-center gap-2 text-lg font-semibold">
                  <Target className="h-5 w-5 text-primary" />
                  {t.actionableSignals}
              </h3>
              {data.signals.length > 0 ? (
                  <div className="grid grid-cols-1 gap-4 lg:grid-cols-2">
                      {data.signals.map((signal, index) => (
                          <SignalCard key={index} signal={signal} lang={lang} />
                      ))}
                  </div>
              ) : (
                  <div className="flex flex-col items-center justify-center rounded-md border-2 border-dashed py-12 text-center">
                      <AuraAcademyLogo iconOnly className="h-10 w-10 text-muted-foreground opacity-30" />
                      <p className="mt-2 text-sm text-muted-foreground">{t.noSignals}</p>
                  </div>
              )}
          </div>
          
          <Alert>
              <Info className="h-4 w-4" />
              <AlertTitle>{t.disclaimerTitle}</AlertTitle>
              <AlertDescription>
                  {t.disclaimer}
              </AlertDescription>
          </Alert>
        </CardContent>
      </Card>
      
      {/* This component is hidden and only used for generating the shareable image */}
      <div className="absolute -left-[9999px] top-0">
          <div ref={shareableImageRef}>
            {data && <ShareableImage result={{ ...result, data: { ...data, chartImage: chartImage } }} theme={currentTheme} />}
          </div>
      </div>
    </>
  );
}
